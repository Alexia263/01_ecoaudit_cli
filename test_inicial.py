nombre1 = input("Introduce el nombre del primer componente: ").strip()
nombre2 = input("Introduce el nombre del segundo componente: ").strip()
nombre3 = input("Introduce el nombre del tercer componente: ").strip()
pareja_autora = (nombre1, nombre2, nombre3)
dispositivo = input("Introduce el nombre del dispositivo auditado: ").strip()
potencia_str = input("Introduce la potencia en vatios (W): ").strip()
potencia_w = float(potencia_str)
consumo_wh = potencia_w * 24
print("\n" + "=" * 40)
print("    INFORME DE CONSUMO ENERGÉTICO")
print("=" * 40)
print(f"Componentes: {pareja_autora[0]}, {pareja_autora[1]} y {pareja_autora[2]}")
print(f"Dispositivo auditado: {dispositivo}")
print(f"Potencia: {potencia_w} W")
print(f"Consumo diario estimado: {consumo_wh} Wh")
print("=" * 40)